void Window::draw_text(int x, int y, std::string_view text,
                       u8 r, u8 g, u8 b, int scale) {
    if (!renderer_ || scale < 1) {
        return;
    }
    SDL_SetRenderDrawColor(renderer_, r, g, b, 255);
    int cx = x;
    int cy = y;
    for (char ch : text) {
        if (ch == '\n') {
            cx = x;
            cy += (kFontH + 1) * scale;
            continue;
        }
        const u8* rows = glyph(ch);
        for (int row = 0; row < kFontH; ++row) {
            const u8 bits = rows[row];
            for (int col = 0; col < kFontW; ++col) {
                if (bits & (0x10 >> col)) {
                    SDL_Rect rc{
                        cx + col * scale,
                        cy + row * scale,
                        scale,
                        scale
                    };
                    SDL_RenderFillRect(renderer_, &rc);
                }
            }
        }
        cx += (kFontW + 1) * scale;
    }
}

void Window::draw_overlay_text(std::string_view text) {
    if (!renderer_) {
        return;
    }
    // Count lines / max width for panel.
    int lines = 1;
    int maxc = 0;
    int col = 0;
    for (char ch : text) {
        if (ch == '\n') {
            ++lines;
            maxc = std::max(maxc, col);
            col = 0;
        } else {
            ++col;
        }
    }
    maxc = std::max(maxc, col);
    const int scale = 1;
    const int pw = maxc * (kFontW + 1) * scale + 8;
    const int ph = lines * (kFontH + 1) * scale + 8;
    SDL_SetRenderDrawBlendMode(renderer_, SDL_BLENDMODE_BLEND);
    SDL_SetRenderDrawColor(renderer_, 0, 0, 0, 180);
    SDL_Rect panel{4, 4, pw, ph};
    SDL_RenderFillRect(renderer_, &panel);
    draw_text(8, 8, text, 0, 255, 80, scale);
}

