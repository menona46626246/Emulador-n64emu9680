Window::~Window() {
    destroy();
}

Window::Window(Window&& o) noexcept {
    *this = std::move(o);
}

Window& Window::operator=(Window&& o) noexcept {
    if (this != &o) {
        destroy();
        window_   = std::exchange(o.window_, nullptr);
        renderer_ = std::exchange(o.renderer_, nullptr);
        fb_tex_   = std::exchange(o.fb_tex_, nullptr);
        width_    = o.width_;
        height_   = o.height_;
        fb_w_     = o.fb_w_;
        fb_h_     = o.fb_h_;
        quit_     = o.quit_;
        sdl_owned_ = std::exchange(o.sdl_owned_, false);
    }
    return *this;
}

bool Window::create(const WindowConfig& cfg) {
    destroy();
    quit_ = false;

    bool headless = cfg.headless;
#ifdef N64EMU_HEADLESS
    headless = true;
#endif
    // Auto-headless when no DISPLAY is available on Unix.
#if defined(__unix__) || defined(__APPLE__)
    if (!headless) {
        const char* display = std::getenv("DISPLAY");
        const char* wayland = std::getenv("WAYLAND_DISPLAY");
        if ((display == nullptr || display[0] == '\0') &&
            (wayland == nullptr || wayland[0] == '\0')) {
            N64_WARN("No DISPLAY/WAYLAND_DISPLAY — forcing SDL dummy video driver");
            headless = true;
        }
    }
#endif

    if (headless) {
        // Must be set before SDL_Init.
        SDL_setenv("SDL_VIDEODRIVER", "dummy", 1);
        SDL_setenv("SDL_AUDIODRIVER", "dummy", 1);
    }

    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS | SDL_INIT_TIMER) != 0) {
        N64_ERROR("SDL_Init failed: {}", SDL_GetError());
        return false;
    }
    sdl_owned_ = true;

    Uint32 flags = SDL_WINDOW_ALLOW_HIGHDPI;
    if (cfg.resizable) {
        flags |= SDL_WINDOW_RESIZABLE;
    }

    window_ = SDL_CreateWindow(
        cfg.title.c_str(),
        SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
        cfg.width, cfg.height,
        flags);

    if (!window_) {
        N64_ERROR("SDL_CreateWindow failed: {}", SDL_GetError());
        destroy();
        return false;
    }

    Uint32 rflags = SDL_RENDERER_ACCELERATED;
    if (cfg.vsync) {
        rflags |= SDL_RENDERER_PRESENTVSYNC;
    }
    renderer_ = SDL_CreateRenderer(window_, -1, rflags);
    if (!renderer_) {
        // Fallback to software renderer (needed for dummy driver).
        renderer_ = SDL_CreateRenderer(window_, -1, SDL_RENDERER_SOFTWARE);
    }
    if (!renderer_) {
        N64_ERROR("SDL_CreateRenderer failed: {}", SDL_GetError());
        destroy();
        return false;
    }

    SDL_SetRenderDrawBlendMode(renderer_, SDL_BLENDMODE_BLEND);
    width_  = cfg.width;
    height_ = cfg.height;

    N64_INFO("Window created {}x{} (driver={}, headless={})",
             width_, height_, SDL_GetCurrentVideoDriver(), headless);
    return true;
}

void Window::destroy() {
    if (fb_tex_) {
        SDL_DestroyTexture(fb_tex_);
        fb_tex_ = nullptr;
    }
    if (renderer_) {
        SDL_DestroyRenderer(renderer_);
        renderer_ = nullptr;
    }
    if (window_) {
        SDL_DestroyWindow(window_);
        window_ = nullptr;
    }
    if (sdl_owned_) {
        SDL_Quit();
        sdl_owned_ = false;
    }
    fb_w_ = fb_h_ = 0;
}

bool Window::poll_events(const EventCallback& on_event) {
    SDL_Event ev;
    while (SDL_PollEvent(&ev)) {
        if (on_event) {
            on_event(ev);
        }
        switch (ev.type) {
        case SDL_QUIT:
            quit_ = true;
            break;
        case SDL_WINDOWEVENT:
            if (ev.window.event == SDL_WINDOWEVENT_SIZE_CHANGED) {
                width_  = ev.window.data1;
                height_ = ev.window.data2;
            }
            break;
        case SDL_KEYDOWN:
            if (ev.key.keysym.sym == SDLK_ESCAPE) {
                quit_ = true;
            }
            break;
        default:
            break;
        }
    }
    return !quit_;
}

void Window::clear(u8 r, u8 g, u8 b, u8 a) {
    if (!renderer_) {
        return;
    }
    SDL_SetRenderDrawColor(renderer_, r, g, b, a);
    SDL_RenderClear(renderer_);
}

void Window::present() {
    if (!renderer_) {
        return;
    }
    SDL_RenderPresent(renderer_);
}

void Window::draw_framebuffer(const u8* rgba, int w, int h) {
    if (!renderer_ || !rgba || w <= 0 || h <= 0) {
        return;
    }
    if (!fb_tex_ || fb_w_ != w || fb_h_ != h) {
        if (fb_tex_) {
            SDL_DestroyTexture(fb_tex_);
        }
        fb_tex_ = SDL_CreateTexture(
            renderer_,
            SDL_PIXELFORMAT_RGBA32, // memory order R,G,B,A on every host
            SDL_TEXTUREACCESS_STREAMING,
            w, h);
        fb_w_ = w;
        fb_h_ = h;
        if (!fb_tex_) {
            N64_ERROR("SDL_CreateTexture failed: {}", SDL_GetError());
            return;
        }
    }
    SDL_UpdateTexture(fb_tex_, nullptr, rgba, w * 4);
    SDL_RenderCopy(renderer_, fb_tex_, nullptr, nullptr);
}

void Window::set_title(std::string_view title) {
    if (window_) {
        SDL_SetWindowTitle(window_, std::string(title).c_str());
    }
}

